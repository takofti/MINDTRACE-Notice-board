export function translate(
  language: UILanguage,
  key: string,
  vars?: Record<string, string | number>
): string {
  const template = language === 'ru' ? RU[key] ?? key : key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`
  )
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const language = useSettings((state) => state.settings.ui.language)
  return useMemo(
    () => (key: string, vars?: Record<string, string | number>) => translate(language, key, vars),
    [language]
  )
}

export function tNow(key: string, vars?: Record<string, string | number>): string {
  return translate(useSettings.getState().settings.ui.language, key, vars)
}

export function localeFor(language: UILanguage): string {
  return language === 'ru' ? 'ru-RU' : 'en-US'
}

export function useLocale(): string {
  const language = useSettings((state) => state.settings.ui.language)
  return localeFor(language)
}

